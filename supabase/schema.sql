create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  timezone text not null default 'America/Santiago',
  calories_target integer not null default 2200 check (calories_target between 800 and 8000),
  protein_target integer not null default 160 check (protein_target between 20 and 500),
  steps_target integer not null default 7000 check (steps_target between 0 and 100000),
  weight_target numeric(6,2),
  waist_target numeric(6,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.daily_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  log_date date not null,
  weight_kg numeric(6,2),
  waist_cm numeric(6,2),
  sleep_score smallint check (sleep_score between 1 and 5),
  energy_score smallint check (energy_score between 1 and 5),
  hunger_score smallint check (hunger_score between 1 and 5),
  cannabis boolean,
  calories integer check (calories >= 0),
  protein_g integer check (protein_g >= 0),
  steps integer check (steps >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, log_date)
);

create table if not exists public.exercise_library (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  category text not null check (category in ('push','pull','legs','core')),
  primary_muscle text not null,
  pattern text not null,
  equipment text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.routine_templates (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  day_order integer not null check (day_order between 1 and 7),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, name),
  unique (user_id, day_order)
);

create table if not exists public.routine_exercises (
  id uuid primary key default gen_random_uuid(),
  routine_id uuid not null references public.routine_templates(id) on delete cascade,
  exercise_id bigint not null references public.exercise_library(id),
  position integer not null,
  target_sets integer not null default 2 check (target_sets between 1 and 10),
  rep_min integer not null default 8 check (rep_min between 1 and 100),
  rep_max integer not null default 12 check (rep_max between 1 and 100),
  rir_target integer not null default 3 check (rir_target between 0 and 10),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (routine_id, position)
);

create table if not exists public.workout_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  routine_id uuid references public.routine_templates(id) on delete set null,
  session_date date not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workout_exercises (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.workout_sessions(id) on delete cascade,
  planned_routine_exercise_id uuid references public.routine_exercises(id) on delete set null,
  exercise_id bigint not null references public.exercise_library(id),
  position integer not null,
  created_at timestamptz not null default now(),
  unique (session_id, position)
);

create table if not exists public.workout_sets (
  id uuid primary key default gen_random_uuid(),
  workout_exercise_id uuid not null references public.workout_exercises(id) on delete cascade,
  set_number integer not null,
  weight_kg numeric(7,2),
  reps integer check (reps between 0 and 500),
  rir integer check (rir between 0 and 10),
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workout_exercise_id, set_number)
);

create table if not exists public.meal_templates (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  calories integer not null default 0,
  protein_g integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.walking_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  session_date date not null,
  started_at timestamptz,
  finished_at timestamptz,
  steps integer,
  distance_km numeric(7,2),
  created_at timestamptz not null default now()
);

create index if not exists daily_logs_user_date_idx on public.daily_logs(user_id, log_date desc);
create index if not exists workout_sessions_user_date_idx on public.workout_sessions(user_id, session_date desc);
create index if not exists routine_templates_user_idx on public.routine_templates(user_id);
create index if not exists routine_exercises_routine_idx on public.routine_exercises(routine_id);
create index if not exists workout_exercises_session_idx on public.workout_exercises(session_id);
create index if not exists workout_sets_exercise_idx on public.workout_sets(workout_exercise_id);

