create or replace function public.seed_default_routines(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  push_a uuid;
  pull_a uuid;
  legs_a uuid;
  push_b uuid;
  pull_b uuid;
  legs_b uuid;
begin
  if exists (select 1 from public.routine_templates where user_id = p_user_id) then
    return;
  end if;

  insert into public.routine_templates(user_id,name,day_order) values (p_user_id,'Push A',1) returning id into push_a;
  insert into public.routine_templates(user_id,name,day_order) values (p_user_id,'Pull A',2) returning id into pull_a;
  insert into public.routine_templates(user_id,name,day_order) values (p_user_id,'Legs A',3) returning id into legs_a;
  insert into public.routine_templates(user_id,name,day_order) values (p_user_id,'Push B',4) returning id into push_b;
  insert into public.routine_templates(user_id,name,day_order) values (p_user_id,'Pull B',5) returning id into pull_b;
  insert into public.routine_templates(user_id,name,day_order) values (p_user_id,'Legs B',6) returning id into legs_b;

  insert into public.routine_exercises(routine_id,exercise_id,position,target_sets,rep_min,rep_max,rir_target)
  select push_a,id,pos,2,rmin,rmax,3 from (values
    ('chest-press-machine',1,8,12),('incline-dumbbell-press',2,8,12),('shoulder-press-machine',3,8,12),('lateral-raise',4,12,20),('triceps-pushdown',5,10,15)
  ) v(slug,pos,rmin,rmax) join public.exercise_library e using(slug);

  insert into public.routine_exercises(routine_id,exercise_id,position,target_sets,rep_min,rep_max,rir_target)
  select pull_a,id,pos,2,rmin,rmax,3 from (values
    ('lat-pulldown',1,8,12),('seated-row',2,8,12),('chest-supported-row',3,8,12),('rear-delt-fly',4,12,20),('biceps-curl',5,10,15)
  ) v(slug,pos,rmin,rmax) join public.exercise_library e using(slug);

  insert into public.routine_exercises(routine_id,exercise_id,position,target_sets,rep_min,rep_max,rir_target)
  select legs_a,id,pos,2,rmin,rmax,3 from (values
    ('leg-press',1,8,12),('romanian-deadlift',2,8,10),('leg-curl',3,10,15),('calf-raise',4,10,15),('plank',5,30,45)
  ) v(slug,pos,rmin,rmax) join public.exercise_library e using(slug);

  insert into public.routine_exercises(routine_id,exercise_id,position,target_sets,rep_min,rep_max,rir_target)
  select push_b,id,pos,2,rmin,rmax,3 from (values
    ('incline-machine-press',1,8,12),('chest-press-machine',2,8,12),('pec-deck',3,10,15),('cable-lateral-raise',4,12,20),('overhead-triceps-extension',5,10,15)
  ) v(slug,pos,rmin,rmax) join public.exercise_library e using(slug);

  insert into public.routine_exercises(routine_id,exercise_id,position,target_sets,rep_min,rep_max,rir_target)
  select pull_b,id,pos,2,rmin,rmax,3 from (values
    ('neutral-lat-pulldown',1,8,12),('one-arm-dumbbell-row',2,8,12),('straight-arm-pulldown',3,12,15),('face-pull',4,12,20),('hammer-curl',5,10,15)
  ) v(slug,pos,rmin,rmax) join public.exercise_library e using(slug);

  insert into public.routine_exercises(routine_id,exercise_id,position,target_sets,rep_min,rep_max,rir_target)
  select legs_b,id,pos,2,rmin,rmax,3 from (values
    ('hack-squat',1,8,12),('hip-thrust',2,8,12),('leg-extension',3,10,15),('leg-curl',4,10,15),('calf-raise',5,10,15)
  ) v(slug,pos,rmin,rmax) join public.exercise_library e using(slug);

  insert into public.meal_templates(user_id,name,calories,protein_g) values
    (p_user_id,'Batido de proteína',250,30),
    (p_user_id,'Pollo + ensalada',480,50),
    (p_user_id,'Atún + huevos',420,42),
    (p_user_id,'Cena Shabat estimada',800,55);
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id,display_name,timezone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email,'@',1)),
    coalesce(new.raw_user_meta_data->>'timezone','America/Santiago')
  )
  on conflict (id) do nothing;
  perform public.seed_default_routines(new.id);
  return new;
end;
$$;

